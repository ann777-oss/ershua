const SHAKEN_RE = /……|沉默|停住|停了|烟灰|手指|抖|顿了顿/

export function fallbackAsk(characterId, question) {
  const rules = QA[characterId] || []
  for (const r of rules) {
    if (r.keys.some(k => question.includes(k))) {
      return { text: r.a, shaken: SHAKEN_RE.test(r.a) }
    }
  }
  return { text: GENERIC[characterId] || '……', shaken: false }
}

export function fallbackShow(characterId, evidenceId) {
  return SHOW_REACTIONS[characterId]?.[evidenceId] || { text: GENERIC[characterId] || '……', shaken: false }
}

export function fallbackSuggestions(characterId) {
  return SUGGESTIONS[characterId] || []
}
